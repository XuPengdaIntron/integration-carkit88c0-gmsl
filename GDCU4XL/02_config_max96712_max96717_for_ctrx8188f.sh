#!/bin/bash

I2C_BUS=${1:-8}
set -x

# MAX96712
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0x13 0x40 && sleep 0.1 # Do a full reset
i2ctransfer -f -y $I2C_BUS w3@0x29 0x00 0x00 0x56 && sleep 0.1 # Change I2C address from 0x29 to 0x2b

i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0x18 0x0f && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0xf0 0x62 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0xf1 0xea && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0xf4 0x0f && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x08 0xa2 0xf7 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0x04 0xff && sleep 0.1

i2ctransfer -f -y $I2C_BUS w3@0x2b 0x08 0xA3 0xE4 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x08 0xA4 0xE4 && sleep 0.1

# 4 lanes
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x0A 0xC0 && sleep 0.1 
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x4A 0xC0 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x8A 0xC0 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0xCA 0xC0 && sleep 0.1

# 2*4 mode
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x08 0xA0 0x04 && sleep 0.1

# Link A
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x0B 0x07 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x0C 0x00 && sleep 0.1 # Set to default value only
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x0D 0x2C && sleep 0.1 # Set to RAW12
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x0E 0x2C && sleep 0.1 # Set to RAW12
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x0F 0x00 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x10 0x00 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x11 0x01 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x12 0x01 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x2D 0x15 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x09 0x73 0x01 && sleep 0.1 # ALT_MEM_MAP12

i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1c 0x00 0xf4 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1d 0x00 0xf4 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1e 0x00 0xf4 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1f 0x00 0xf4 && sleep 0.1

i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0x15 0x34 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0x18 0x34 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0x1b 0x34 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0x1e 0x34 && sleep 0.1

i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1c 0x00 0xf5 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1d 0x00 0xf5 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1e 0x00 0xf5 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x1f 0x00 0xf5 && sleep 0.1

# Disable all links
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0x06 0xF0 && sleep 0.1

# Enable Link A
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0x06 0xF1 && sleep 0.1

i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0x10 0x22 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x00 0x11 0x22 && sleep 0.1

# MAX 96717
i2ctransfer -f -y $I2C_BUS w3@0x61 0x00 0x10 0x81 && sleep 0.1 # Do a full reset
i2ctransfer -f -y $I2C_BUS w3@0x42 0x00 0x00 0xC2 && sleep 0.1 # change I2C address from 42 to 61

i2ctransfer -f -y $I2C_BUS w3@0x61 0x00 0x02 0x03 && sleep 0.2 # Enable Video Stream
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x30 0x00 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x83 0x00 && sleep 0.1 # Set to Pixel mode

# The following settings 0x331, 0x332, 0x333, 0x334, 0x335 are set to default values only
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x31 0x70 && sleep 0.1 # 0b00110000 Set to 4 data lanes
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x32 0xE0 && sleep 0.1 # Sensor Lane 3 to Serializer Lane 3, 2 to 2
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x33 0x04 && sleep 0.1 # Sensor Lane 1 to Serializer Lane 1, 0 to 0
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x34 0x00 && sleep 0.1 # Set to normal polarity for data lane
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x35 0x00 && sleep 0.1 # Set to normal polarity for data lane

i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x08 0x64 && sleep 0.1 # set to default value only
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x11 0x40 && sleep 0.1 # set to default value only
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x18 0x6c && sleep 0.1 # Set to RAW12
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x13 0x40 && sleep 0.1 # Send 12-bit pixel as 24 bit
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x1E 0x38 && sleep 0.1 

i2ctransfer -f -y $I2C_BUS w3@0x61 0x00 0x02 0x43 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x30 0x08 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x61 0x03 0x30 0x00 && sleep 0.1

# SPI related
i2ctransfer -f -y $I2C_BUS w3@0x61 0x01 0x73 0x1e && sleep 0.1  # SCK 分频 = 5MHz
i2ctransfer -f -y $I2C_BUS w3@0x61 0x01 0x74 0x1e && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x61 0x01 0x75 0x1e && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x61 0x01 0x76 0x04 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x61 0x01 0x72 0x0C && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x61 0x01 0x70 0x0b && sleep 0.1  # MAX96717 SPI 主模式

i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0xE9 0x00 && sleep 0.1  # SPI 链路选择 = GMSL Link A
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0xE6 0x03 && sleep 0.1
i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0xE0 0x09 && sleep 0.1  # SPI 从模式激活


i2ctransfer -f -y $I2C_BUS w3@0x2b 0x04 0x0b 0x62 && sleep 0.1
